/**
 * Capability-thread heatmap — pure replay over `register/activities.jsonl`.
 *
 * Output: `claude-kindling/register/heatmap.json` with shape:
 *   {
 *     _meta: { description, version, lastRegenerated },
 *     threads: { [threadId]: [{ sanityId, tier, packRef }] }
 *   }
 *
 * Threads come from the `capabilityThreads` field on activity `created` events.
 * That field is populated by the orchestrator at the same time the Sanity
 * `created` event fires. Older events may not have it; those are skipped silently.
 *
 * Idempotent: re-running on the same events produces the same output (modulo
 * `lastRegenerated`). Each thread's entry list is deduplicated by sanityId+tier.
 */

import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { readEvents } from '../../register/helper';

export interface HeatmapEntry {
  sanityId: string;
  tier: 'primary' | 'secondary';
  packRef: string;
}

export interface Heatmap {
  _meta: {
    description: string;
    version: number;
    lastRegenerated: string;
  };
  threads: Record<string, HeatmapEntry[]>;
}

const HEATMAP_VERSION = 1;
const DESCRIPTION =
  'Capability thread coverage map. Regenerated by build-mode and patrol-mode from JSONL replay. ' +
  'Each thread maps to an array of {sanityId, tier, packRef} entries.';

/**
 * Build (don't write) the heatmap from current `register/activities.jsonl` state.
 * Pure — no side effects. Used by tests and by `writeHeatmap()`.
 */
export async function buildHeatmap(): Promise<Heatmap> {
  const events = await readEvents('activity');
  const threads: Record<string, HeatmapEntry[]> = {};

  // Group entries by threadId, deduplicating by composite key (sanityId+tier).
  const seen = new Map<string, Set<string>>();

  for (const e of events) {
    if (e.event !== 'created') continue;
    const sanityId = (e.sanityId as string) ?? (e.kindlingId as string);
    if (!sanityId) continue;
    const packRef = (e.packRef as string) ?? '';
    const ct = e.capabilityThreads;
    if (!Array.isArray(ct)) continue;
    for (const entry of ct as Array<{ id?: string; primary?: boolean }>) {
      if (!entry || typeof entry.id !== 'string') continue;
      const tier: HeatmapEntry['tier'] = entry.primary === true ? 'primary' : 'secondary';
      const composite = `${sanityId}|${tier}`;
      if (!seen.has(entry.id)) {
        seen.set(entry.id, new Set());
        threads[entry.id] = [];
      }
      if (!seen.get(entry.id)!.has(composite)) {
        seen.get(entry.id)!.add(composite);
        threads[entry.id].push({ sanityId, tier, packRef });
      }
    }
  }

  // Sort entries within each thread for deterministic output.
  for (const id of Object.keys(threads)) {
    threads[id].sort((a, b) => {
      if (a.sanityId !== b.sanityId) return a.sanityId < b.sanityId ? -1 : 1;
      return a.tier < b.tier ? -1 : a.tier > b.tier ? 1 : 0;
    });
  }

  return {
    _meta: {
      description: DESCRIPTION,
      version: HEATMAP_VERSION,
      lastRegenerated: new Date().toISOString(),
    },
    threads,
  };
}

/**
 * Idempotent overwrite of `register/heatmap.json` with the given heatmap.
 * Returns the absolute path written.
 */
export async function writeHeatmap(h: Heatmap): Promise<string> {
  const out = resolve(__dirname, '..', '..', 'register', 'heatmap.json');
  await writeFile(out, JSON.stringify(h, null, 2) + '\n', 'utf8');
  return out;
}
