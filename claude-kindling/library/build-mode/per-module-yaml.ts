/**
 * Per-module YAML writer — produces the denormalised summary file at
 * `claude-kindling/register/per-module/module-{P}-{M}.yaml` after a module's
 * content has been built.
 *
 * The YAML caches the derived bucket plus key activity ids so reading a module's
 * current state doesn't require replaying every event. Per `register/README.md`,
 * this file is regenerated from JSONL — never hand-edited.
 *
 * Idempotent: rerun overwrites the file. Manual YAML emission keeps us off the
 * dependency tree (no `js-yaml` introduction). The YAML we produce is intentionally
 * boring — strings quoted, lists in block style — so a future swap to `js-yaml`
 * is trivial.
 */

import { writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { readEvents, replayBucketState } from '../../register/helper';
import type { ModuleSpec } from './spec-parser';

/**
 * Structural shape of the orchestrator's `RunContext` (the parts this writer
 * actually reads). Defined locally to avoid importing `orchestrator.ts` —
 * which would create a circular dependency at module-load time.
 */
export interface PerModuleYamlCtx {
  session: string;
  spec: ModuleSpec;
  created: { type: string; id: string; title: string }[];
  hardFailures: { id: string; criteria: string[] }[];
  softWarnings: { id: string; criteria: string[] }[];
}

export async function writePerModuleYaml(
  spec: ModuleSpec,
  ctx: PerModuleYamlCtx,
): Promise<string> {
  const { pack, module: mod } = parsePackModule(spec.kindlingId);
  const out = resolve(
    __dirname,
    '..',
    '..',
    'register',
    'per-module',
    `module-${pack}-${mod}.yaml`,
  );
  if (!existsSync(dirname(out))) {
    await mkdir(dirname(out), { recursive: true });
  }
  const yaml = await renderYaml(spec, ctx);
  await writeFile(out, yaml, 'utf8');
  return out;
}

async function renderYaml(spec: ModuleSpec, ctx: PerModuleYamlCtx): Promise<string> {
  const moduleEvents = await readEvents('module');
  const bucket = replayBucketState(moduleEvents, spec.kindlingId) ?? 'unknown';

  const approachIds = ctx.created
    .filter((c) => c.type === 'approach')
    .map((c) => c.id);
  const activityIds = ctx.created
    .filter((c) => c.type === 'activity')
    .map((c) => c.id);

  const lines: string[] = [];
  lines.push(`# Per-module summary — regenerated by build-mode orchestrator.`);
  lines.push(`# Source of truth is the JSONL register; this file is a denormalised cache.`);
  lines.push('');
  lines.push(`module: ${q(spec.kindlingId)}`);
  lines.push(`pack: ${q(spec.packRef)}`);
  lines.push(`bucket: ${q(bucket)}`);
  lines.push(`session: ${q(ctx.session)}`);
  lines.push(`lastBuiltAt: ${q(new Date().toISOString())}`);
  lines.push(`targetUnderstanding: ${q(spec.targetUnderstanding ?? '')}`);
  if (spec.ageRange) {
    lines.push(`ageRange:`);
    lines.push(`  min: ${spec.ageRange.min}`);
    lines.push(`  max: ${spec.ageRange.max}`);
  } else {
    lines.push(`ageRange: null`);
  }
  lines.push(`subjects:`);
  if (spec.subjects.length === 0) lines.push(`  []`);
  else for (const s of spec.subjects) lines.push(`  - ${q(s)}`);

  lines.push(`approaches:`);
  if (approachIds.length === 0) lines.push(`  []`);
  else for (const id of approachIds) lines.push(`  - ${q(id)}`);

  lines.push(`activities:`);
  if (activityIds.length === 0) lines.push(`  []`);
  else for (const id of activityIds) lines.push(`  - ${q(id)}`);

  lines.push(`hardFailures:`);
  if (ctx.hardFailures.length === 0) lines.push(`  []`);
  else
    for (const h of ctx.hardFailures) {
      lines.push(`  - id: ${q(h.id)}`);
      lines.push(`    criteria:`);
      for (const c of h.criteria) lines.push(`      - ${q(c)}`);
    }

  lines.push(`softWarnings:`);
  if (ctx.softWarnings.length === 0) lines.push(`  []`);
  else
    for (const w of ctx.softWarnings) {
      lines.push(`  - id: ${q(w.id)}`);
      lines.push(`    criteria:`);
      for (const c of w.criteria) lines.push(`      - ${q(c)}`);
    }

  lines.push('');
  return lines.join('\n');
}

function parsePackModule(kindlingId: string): { pack: number; module: number } {
  const m = /^module\.(\d+)\.(\d+)\./.exec(kindlingId);
  if (!m) {
    throw new Error(
      `per-module-yaml: cannot parse pack/module indices from kindlingId \`${kindlingId}\``,
    );
  }
  return { pack: parseInt(m[1], 10), module: parseInt(m[2], 10) };
}

/** Conservative YAML string quoting — always quote, escape backslash + double-quote. */
function q(s: string): string {
  const escaped = s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  return `"${escaped}"`;
}
